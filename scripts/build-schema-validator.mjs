// Compiles the JSON Schema into a plain JavaScript validator, ahead of time.
//
// ajv builds its validators with `new Function(...)`, which a strict
// Content-Security-Policy blocks: keeping that path would mean allowing
// 'unsafe-eval' for the whole site. Compiling here instead lets the page
// ship a validator that is ordinary code.
//
//   node scripts/build-schema-validator.mjs           write the validator
//   node scripts/build-schema-validator.mjs --check   fail if it is out of date
//
// The output is committed, and both the build (`prebuild`, in --check mode) and
// test/schema-validate.test.ts fail if it drifts from the schema. The build
// only checks — it never rewrites the file, because a build that quietly
// regenerates would hide a generated file someone forgot to commit.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { _ } from "ajv";
import schema from "../schema/part-number-canvas.v1.schema.json" with { type: "json" };
import ajvPackage from "ajv/package.json" with { type: "json" };
import ajvFormatsPackage from "ajv-formats/package.json" with { type: "json" };

const OUTPUT = new URL("../src/lib/schema/validator.generated.mjs", import.meta.url);

// Stamped into the file: ajv's output changes with its version, so a version
// bump shows up as a diff here instead of as a drift-test failure with no cause
const HEADER = `// Generated by scripts/build-schema-validator.mjs from
// schema/part-number-canvas.v1.schema.json — do not edit by hand.
// ajv ${ajvPackage.version}, ajv-formats ${ajvFormatsPackage.version}
// Regenerate with: node scripts/build-schema-validator.mjs
import { fullFormats as formats } from "ajv-formats/dist/formats.js";
import ucs2lengthModule from "ajv/dist/runtime/ucs2length.js";
// that file is CommonJS, and bundlers disagree on whether a default import of
// one lands on the function or on the module object holding it
const ucs2length = ucs2lengthModule.default ?? ucs2lengthModule;
`;

/**
 * ajv emits its string-length helper as a CommonJS `require` even when asked
 * for an ES module, which throws "require is not defined" in the browser the
 * first time a maxLength is checked. The import above replaces it.
 */
const UCS2_REQUIRE = 'require("ajv/dist/runtime/ucs2length").default';

/** The source of the committed validator, so the build and the drift test agree on it. */
export function generateValidatorSource() {
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    // `formats` names the import above: the generated code refers to the real
    // format implementations instead of inlining functions it cannot serialize
    code: { source: true, esm: true, formats: _`formats` },
  });
  addFormats(ajv);
  const code = standaloneCode(ajv, ajv.compile(schema));
  if (!code.includes(UCS2_REQUIRE)) {
    throw new Error(`expected ajv to emit ${UCS2_REQUIRE}; check whether the workaround is still needed`);
  }
  const source = HEADER + code.replaceAll(UCS2_REQUIRE, "ucs2length");
  // Any other CommonJS helper ajv adds (a new keyword, a new ajv version) would
  // throw "require is not defined" in the browser the moment the module loads,
  // so stop here rather than write a file that cannot run.
  const leftover = source.match(/\brequire\([^)]*\)/);
  if (leftover) {
    throw new Error(
      `ajv emitted a CommonJS require this script does not handle: ${leftover[0]}. ` +
        "Add an import for it to HEADER and replace it the way UCS2_REQUIRE is replaced.",
    );
  }
  return source;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const source = generateValidatorSource();
  if (process.argv.includes("--check")) {
    const committed = readFileSync(OUTPUT, "utf-8");
    if (committed !== source) {
      console.error(
        `${OUTPUT.pathname} is out of date.\n` +
          "Run `npm run build:validator` and commit the result.",
      );
      process.exit(1);
    }
    console.log("build-schema-validator: the committed validator matches the schema");
  } else {
    writeFileSync(OUTPUT, source);
    console.log(`wrote ${OUTPUT.pathname}`);
  }
}
